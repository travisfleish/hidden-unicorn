import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'

const REPO = new URL('..', import.meta.url).pathname
const OUT_DIR = path.join(REPO, 'public/headshots')
const DATA_PY = path.join(path.dirname(new URL(import.meta.url).pathname), 'nba-player-index.py')

fs.mkdirSync(OUT_DIR, { recursive: true })

const norm = (s) =>
  s.normalize('NFD').replace(/[̀-ͯ]/g, '')
    .replace(/[‘’']/g, '')
    .toLowerCase()
    .replace(/\./g, '')
    .replace(/\s+/g, ' ')
    .trim()

// --- parse nba_api data.py player index: [id, last, first, full_name, is_active]
const py = fs.readFileSync(DATA_PY, 'utf8')
const block = py.slice(py.indexOf('players = ['))
const rowRe = /\[\s*(\d+)\s*,\s*"((?:[^"\\]|\\.)*)"\s*,\s*"((?:[^"\\]|\\.)*)"\s*,\s*"((?:[^"\\]|\\.)*)"\s*,\s*(True|False)\s*\]/g
const index = new Map() // normName -> [{id, active}]
let mt
while ((mt = rowRe.exec(block))) {
  const [, id, , , full, active] = mt
  const k = norm(full)
  if (!index.has(k)) index.set(k, [])
  index.get(k).push({ id: Number(id), active: active === 'True' })
}
console.log(`parsed ${index.size} unique names from data.py`)

// --- player names from the model export (full roster), plus any curated names in lib/data.ts
const distTs = fs.readFileSync(path.join(REPO, 'lib/offensiveArchetypeDistances.ts'), 'utf8')
const dataTs = fs.readFileSync(path.join(REPO, 'lib/data.ts'), 'utf8')
const names = [...new Set([
  ...[...distTs.matchAll(/"playerName":\s*"([^"]+)"/g)].map((m) => m[1]),
  ...[...dataTs.matchAll(/name:'([^']+)'/g)].map((m) => m[1]),
])].filter((n) => n !== 'League player')

// manual overrides for names that don't line up with the official index
const OVERRIDE = {
  'Bobby Portis': 1626171,
}

const resolved = {}
const missing = []
for (const name of names) {
  if (OVERRIDE[name]) { resolved[name] = OVERRIDE[name]; continue }
  const hits = index.get(norm(name))
  if (!hits || hits.length === 0) { missing.push(name); continue }
  const pick = hits.find((h) => h.active) ?? hits[0]
  resolved[name] = pick.id
}

console.log(`matched ${Object.keys(resolved).length}/${names.length}`)
if (missing.length) console.log('UNMATCHED:', missing)

// --- download headshots from the NBA CDN
const SIZES = { full: '1040x760', small: '260x190' }
let ok = 0
const bad = []
for (const [name, id] of Object.entries(resolved)) {
  const dest = path.join(OUT_DIR, `${id}.png`)
  if (fs.existsSync(dest) && fs.statSync(dest).size > 5000) { ok++; continue }
  const url = `https://cdn.nba.com/headshots/nba/latest/${SIZES.full}/${id}.png`
  try {
    execFileSync('curl', ['-sfL', '-m', '30', '-o', dest, url])
    const sz = fs.statSync(dest).size
    if (sz < 3000) { bad.push(`${name} (${id}) tiny ${sz}b`); }
    else ok++
  } catch (e) {
    bad.push(`${name} (${id}) ${e.message}`)
  }
}
console.log(`downloaded/verified ${ok} headshots -> ${OUT_DIR}`)
if (bad.length) console.log('DOWNLOAD ISSUES:', bad)

// --- emit lib/headshots.ts : player name -> NBA person id
const entries = names
  .filter((n) => resolved[n])
  .map((n) => `  ${JSON.stringify(n)}: ${resolved[n]},`)
  .join('\n')
const file = `// AUTO-GENERATED by scripts/pull-headshots.mjs — do not edit by hand.
// Maps player name -> NBA.com person id. Images live in public/headshots/<id>.png
// Source: nba_api static player index + https://cdn.nba.com/headshots/nba/latest/1040x760/<id>.png

export const headshotIds: Record<string, number> = {
${entries}
}

/** Public path to a player's headshot, or null if we don't have one. */
export function headshotUrl(name: string): string | null {
  const id = headshotIds[name]
  return id ? \`/headshots/\${id}.png\` : null
}
`
fs.writeFileSync(path.join(REPO, 'lib/headshots.ts'), file)
console.log('wrote lib/headshots.ts')
